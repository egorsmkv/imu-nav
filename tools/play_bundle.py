#!/usr/bin/env python3
"""Validate Play bundles and sign a separate copy using an existing, pinned upload key."""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
import zipfile

from benchmark_signing import credential_variables, fingerprint
from update_app_version import MAX_VERSION_CODE, one, release_version
from verify_android_pages import elf_errors, verify_apk

ANDROID = '{http://schemas.android.com/apk/res/android}'


def run(arguments, env=None):
    """Capture diagnostics so signing failures cannot disclose aliases or key-parser output."""
    result = subprocess.run([str(arg) for arg in arguments], env=env, capture_output=True, check=False, timeout=600)
    if result.returncode:
        raise ValueError('Bundle tool or signing verification failed (tool diagnostics withheld)')
    return result.stdout.decode('utf-8')


def unsigned_archive(bundle):
    """Fail closed on corrupt ZIPs, ambiguous entries, unsafe paths or existing signatures."""
    with zipfile.ZipFile(bundle) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)) or archive.testzip() is not None:
            raise ValueError('Corrupt or duplicate bundle entries')
        for name in names:
            path = PurePosixPath(name)
            if path.is_absolute() or '..' in path.parts or '\\' in name:
                raise ValueError('Unsafe bundle path')
            if re.fullmatch(r'META-INF/[^/]+\.(SF|RSA|DSA|EC)', name, re.I):
                raise ValueError('Expected an unsigned input bundle')


def manifest_info(xml, gradle, metadata, last_code=None):
    """Compare the built manifest with release sources and the operator's Play Console ceiling."""
    root = ET.fromstring(xml)
    code = int(root.attrib[ANDROID + 'versionCode'])
    name = root.attrib[ANDROID + 'versionName']
    sdk, app = root.find('uses-sdk'), root.find('application')
    if root.attrib['package'] != 'org.imunav.app' or sdk is None or app is None:
        raise ValueError('Unexpected Play application identity or missing manifest elements')
    if app.attrib.get(ANDROID + 'debuggable', 'false') != 'false':
        raise ValueError('Play release must not be debuggable')
    if int(sdk.attrib[ANDROID + 'minSdkVersion']) != 26 or int(sdk.attrib[ANDROID + 'targetSdkVersion']) != 36:
        raise ValueError('Unexpected minimum or target SDK')
    release_version(name)
    if not 0 < code <= MAX_VERSION_CODE:
        raise ValueError('Invalid Play version code')
    if code != int(one(gradle, r'^\s*versionCode = ([0-9]+)\s*$')[1]) or name != one(gradle, r'^\s*versionName = "([^"\n]+)"\s*$')[1]:
        raise ValueError('Built bundle and Gradle versions disagree')
    if code != int(one(metadata, r'^CurrentVersionCode: ([0-9]+)$')[1]) or name != one(metadata, r'^CurrentVersion: (\S+)$')[1]:
        raise ValueError('Built bundle and F-Droid versions disagree')
    if last_code is not None and (not 0 <= last_code <= MAX_VERSION_CODE or code <= last_code):
        raise ValueError('Version code must exceed every previously uploaded Play version code')
    return {'package': root.attrib['package'], 'version_code': code, 'version_name': name, 'min_sdk': 26, 'target_sdk': 36,
            'last_play_version_code': last_code,
            'permissions': sorted(item.attrib[ANDROID + 'name'] for item in root.findall('uses-permission'))}


def bundle_libraries(bundle):
    """Check all packaged ARM64 native dependencies, not just the locally built JNI library."""
    libraries = []
    with zipfile.ZipFile(bundle) as archive:
        for name in sorted(archive.namelist()):
            if '/lib/arm64-v8a/' in name and name.endswith('.so'):
                errors = elf_errors(archive.read(name))
                if errors:
                    raise ValueError(f'{name}: {", ".join(errors)}')
                libraries.append(name)
        for abi in ('arm64-v8a', 'armeabi-v7a'):
            if f'base/lib/{abi}/libimu_nav_jni.so' not in archive.namelist():
                raise ValueError(f'Missing navigation JNI for {abi}')
    return libraries


def verify(bundle, bundletool, zipalign, output, last_code=None):
    """Validate bundle structure, versions, native layout and the APK generated by bundletool."""
    root = Path(__file__).resolve().parents[1]
    output.mkdir(parents=True, exist_ok=True)
    command = ['java', '-jar', bundletool]
    with zipfile.ZipFile(bundle) as archive:
        if archive.testzip() is not None or len(archive.namelist()) != len(set(archive.namelist())):
            raise ValueError('Corrupt or duplicate bundle entries')
    run(command + ['validate', f'--bundle={bundle}'])
    xml = run(command + ['dump', 'manifest', f'--bundle={bundle}', '--module=base'])
    info = manifest_info(xml, (root / 'app/build.gradle.kts').read_text(), (root / 'fdroid/metadata.yml').read_text(), last_code)
    config = json.loads(run(command + ['dump', 'config', f'--bundle={bundle}']))
    if config.get('optimizations', {}).get('uncompressNativeLibraries', {}).get('alignment') != 'PAGE_ALIGNMENT_16K':
        raise ValueError('Bundle does not request 16 KB APK native-library alignment')
    libraries = bundle_libraries(bundle)
    # bundletool uses an SDK debug identity for disposable test APKs, never for the upload AAB.
    with tempfile.TemporaryDirectory(prefix='imunav-apks-') as directory:
        apks = Path(directory) / 'test.apks'
        run(command + ['build-apks', f'--bundle={bundle}', f'--output={apks}', '--mode=universal'])
        apk = Path(directory) / 'universal.apk'
        with zipfile.ZipFile(apks) as archive:
            apk.write_bytes(archive.read('universal.apk'))
        pages = verify_apk(apk, zipalign)
        pages['apk'] = 'bundletool/universal.apk'
        if pages['errors']:
            raise ValueError('Generated APK failed 16 KB checks: ' + '; '.join(pages['errors']))
    info.update(aab_sha256=hashlib.sha256(bundle.read_bytes()).hexdigest(), libraries=libraries, pages=pages,
                runtime_notice='Static validation; run the ARM64 Play release on a 16 KB device before distribution.')
    (output / 'manifest.xml').write_text(xml)
    (output / 'bundle-config.json').write_text(json.dumps(config, indent=2) + '\n')
    (output / 'verification.json').write_text(json.dumps(info, indent=2) + '\n')
    (output / 'SHA256SUMS').write_text(f"{info['aab_sha256']}  {bundle.name}\n")
    return info


def sign(bundle, output, env=None):
    """Restore only the existing release keystore; require the actual Play upload certificate pin."""
    env = dict(os.environ if env is None else env)
    variables = credential_variables('release')
    if not all(env.get(name) for name in variables):
        raise ValueError('All four existing RELEASE key settings are required; no fallback identity')
    expected = fingerprint(env.get('IMUNAV_PLAY_UPLOAD_CERT_SHA256', ''))
    unsigned_archive(bundle)
    if output.exists():
        raise ValueError('Refusing to overwrite a signed bundle')
    with tempfile.TemporaryDirectory(prefix='imunav-play-sign-', dir=env.get('RUNNER_TEMP')) as directory:
        keystore = Path(directory) / 'upload.keystore'
        with keystore.open('xb') as stream:
            os.chmod(keystore, 0o600)
            stream.write(base64.b64decode(env[variables[0]], validate=True))
        certificate = Path(directory) / 'upload.der'
        run(['keytool', '-exportcert', '-keystore', keystore, '-alias', env[variables[2]],
             '-storepass:env', variables[1], '-file', certificate], env)
        if hashlib.sha256(certificate.read_bytes()).hexdigest() != expected:
            raise ValueError('Existing key differs from the Play upload certificate pin')
        staged = Path(directory) / 'signed.aab'
        shutil.copyfile(bundle, staged)
        run(['jarsigner', '-keystore', keystore, '-storepass:env', variables[1], '-keypass:env', variables[3],
             '-digestalg', 'SHA-256', staged, env[variables[2]]], env)
        verify_signature(staged, expected)
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(staged, output)
    return expected


def verify_signature(bundle, expected):
    """Read every payload through Java's cryptographic JAR verifier and check its signer pin."""
    return run(['java', Path(__file__).with_name('VerifyBundleSignature.java'), bundle, fingerprint(expected)])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['verify', 'sign'])
    parser.add_argument('--bundle', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--bundletool', type=Path)
    parser.add_argument('--zipalign', type=Path)
    parser.add_argument('--last-play-version-code', type=int)
    args = parser.parse_args()
    try:
        if args.mode == 'sign':
            actual = sign(args.bundle, args.output)
            print(json.dumps({'upload_certificate_sha256': actual, 'aab': args.output.name}))
        else:
            if not args.bundletool or not args.zipalign:
                raise ValueError('Verification requires bundletool and zipalign')
            print(json.dumps(verify(args.bundle, args.bundletool, args.zipalign, args.output, args.last_play_version_code)))
    except (ValueError, OSError, subprocess.TimeoutExpired, zipfile.BadZipFile, ET.ParseError, KeyError):
        parser.exit(1, 'Play bundle verification/signing failed; check configuration and public validation inputs.\n')


if __name__ == '__main__':
    main()
